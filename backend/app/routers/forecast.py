from fastapi import APIRouter, HTTPException
from app.models import ForecastResponse, RuleEvaluationRequest, RuleEvaluationResponse
from app.services.forecast_engine import generate_live_ml_forecast
from app.services.rule_engine import evaluate_switching_rules

router = APIRouter(prefix="/api/forecast", tags=["Forecast"])

@router.get("/mock", response_model=ForecastResponse)
@router.get("/live", response_model=ForecastResponse)
def get_live_forecast():
    """
    Returns a full 24-hour demand forecast generated by the trained GradientBoostingRegressor
    machine learning model (trained on train_telemetry.csv) with microgrid mode evaluation
    and overload warnings for HackSphere 3.0.
    """
    return generate_live_ml_forecast()

@router.post("/evaluate", response_model=RuleEvaluationResponse)
def evaluate_custom_point(req: RuleEvaluationRequest):
    """
    Evaluates switching rules and overload limit for an arbitrary hour and demand reading.
    Useful for interactive testing, live sliders, and simulations.
    """
    mode, is_overload, rule_reason, alert = evaluate_switching_rules(
        hour=req.hour,
        predicted_demand_kw=req.predicted_demand_kw
    )
    
    # Realistic battery SoC recommendation
    suggested_soc = max(10.0, min(100.0, req.current_battery_soc or 75.0))
    if mode.value == "Renewable Storage Mode":
        suggested_soc = max(18.0, suggested_soc - 4.5)
    else:
        suggested_soc = min(98.0, suggested_soc + 2.5)

    return RuleEvaluationResponse(
        hour=req.hour,
        time_label=f"{req.hour:02d}:00",
        predicted_demand_kw=req.predicted_demand_kw,
        mode=mode,
        is_overload=is_overload,
        rule_reason=rule_reason,
        alert=alert,
        suggested_battery_soc=round(suggested_soc, 1)
    )
